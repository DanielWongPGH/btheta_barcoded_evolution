def get_mouse_timecourse(expt, mouse, include_reseq=True, include_pseudo_derepped=True, 
                         min_depth=10**3, specific_timepoints=[], max_hopping_expectation=10**10):
    ##
    mouse_timepoints = []
    mouse_reads = []
    mouse_depths = [] ## effective depths

    for day in library_meta[expt][mouse]:
        if day in ['smallint', 'cecum'] and day not in specific_timepoints:
            continue

        day_replicates = []
        day_replicate_depths = []
        for (arr_name, arr_index) in library_meta[expt][mouse][day]:
            if arr_name != 'reseq' and not include_pseudo_derepped:
                continue
            if arr_name == 'reseq' and not include_reseq:
                continue

            
            read_array, read_depths = barcode_arrays[arr_name]
            lib_array, (lib_nominal_depth, lib_effective_depth) = read_array[arr_index], read_depths[arr_index]

            hopping_rate = barcode_hopping_rates[arr_name][arr_index]
            if hopping_rate*lib_nominal_depth > max_hopping_expectation:
                continue

            if np.sum(lib_array / lib_nominal_depth * lib_effective_depth) < min_depth:
                continue
            day_replicates.append( lib_array / lib_nominal_depth * lib_effective_depth)
            day_replicate_depths.append(lib_effective_depth)

    
        if len(day_replicates) == 0:
            continue
        summed_reads = np.sum(day_replicates, axis=0, dtype='float')
        summed_depth = np.sum(day_replicate_depths)
        if summed_depth < min_depth:
            continue
        
        # if day == 'smallint': # convert to integer day
        #     day = SMALLINT_DAY
        # if day == 'cecum':
        #     day = CEC_DAY
        mouse_timepoints.append(day)
        mouse_reads.append(summed_reads)
        mouse_depths.append(summed_depth)

    mouse_timepoints, mouse_reads, mouse_depths = mouse_timepoints, np.array(mouse_reads), np.array(mouse_depths)
    if np.any(specific_timepoints):
        # assert np.all([t in mouse_timepoints for t in specific_timepoints])
        timepoint_indices = [mouse_timepoints.index(t) for t in specific_timepoints]
        return specific_timepoints, mouse_reads[timepoint_indices], mouse_depths[timepoint_indices]
    else:
        return np.array(mouse_timepoints), mouse_reads, mouse_depths



def calc_freqs(read_array, depth_array=None):     
    if read_array.ndim > 1:
        if not np.any(depth_array):
            depth_array = np.sum(read_array, axis=1)

        return np.einsum('ij, i->ij', read_array, depth_array**-1.)
    else:
        if not np.any(depth_array):
            depth_array = np.sum(read_array)
        return read_array / depth_array


