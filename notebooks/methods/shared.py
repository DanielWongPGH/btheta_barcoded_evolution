def recipient_trajectory_model(donor_trajectories, recip_init, donor_transmission, recip_transmission, no_engraftment=False):
    # donor_trajectories is a list of donor trajectories = [(donor1_days, donor1_freqs), (donor2_days, donor2_freqs), ...]
    # requires donor_trajectories interpolated over all days in interval
    # this model assumes that the donors behave essentially identically, and we can ignore drift

    donor_days = donor_trajectories[0][0]
    print(len(donor_trajectories))    
    assert np.all(np.diff(donor_days) == 1)
    for other_donor_days, other_donor_freqs in donor_trajectories[1:]:
        assert np.all(donor_days == other_donor_days)
    donor_avg = np.mean([freqs for days, freqs in donor_trajectories], axis=0)

    recip_init = np.array(recip_init)
    recip_transmission  = np.array(recip_transmission)
    
    recip_freqs = np.zeros((len(recip_init), len(donor_days)))
    recip_freqs[:, 0] = recip_init

    for i, day in enumerate(donor_days[1:]):
        mean_freq = (donor_avg[i]*len(donor_trajectories) + np.sum(recip_freqs[:, i])) / (len(recip_init) + len(donor_trajectories))
        effective_fitness = (donor_avg[i+1] - donor_transmission * mean_freq) / ((1- donor_transmission)*donor_avg[i])
        if no_engraftment:
            effective_fitness = 0

        # print(effective_fitness)
        recip_freqs[:, i+1] = (1 - recip_transmission) * effective_fitness * recip_freqs[:, i] + recip_transmission * mean_freq

    return donor_days, recip_freqs

